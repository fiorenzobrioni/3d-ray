"""Generates Rendering/Sky/HosekWilkieData.cs: the RGB coefficients of the
Hosek-Wilkie analytic sky model (Hosek and Wilkie 2012, "An Analytic Model for
Full Spectral Sky-Dome Radiance"; reference implementation version 1.4a),
transcribed unchanged from ArHosekSkyModelData_RGB.h.

The data are published under the 3-clause BSD license, reproduced in the
generated file as the license requires. The file is fetched from the copy that
ships with PBRT-v3 (pbrt-v3/src/ext), byte-identical to the authors' release.

    python3 validation/gen_hosek_wilkie_data.py [path/to/ArHosekSkyModelData_RGB.h]

Layout (per colour channel):
  coefficients: 2 albedos x 10 turbidities x 6 Bezier control points x 9 = 1080 values
  radiance:     2 albedos x 10 turbidities x 6 control points             =  120 values
"""
import pathlib, re, sys, urllib.request

URL = "https://raw.githubusercontent.com/mmp/pbrt-v3/master/src/ext/ArHosekSkyModelData_RGB.h"
src = pathlib.Path(sys.argv[1]).read_text() if len(sys.argv) > 1 else urllib.request.urlopen(URL).read().decode()

license_block = src[src.index("/*") + 2:src.index("*/")].strip("\n")

def array(name):
    m = re.search(r"double\s+" + name + r"\s*\[\]\s*=\s*\{(.*?)\};", src, re.S)
    body = re.sub(r"//[^\n]*", "", m.group(1))
    return [float(v) for v in re.findall(r"[-+]?\d*\.\d+(?:[eE][-+]?\d+)?|[-+]?\d+(?:[eE][-+]?\d+)?", body)]

coef = [array(f"datasetRGB{c}") for c in (1, 2, 3)]
rad = [array(f"datasetRGBRad{c}") for c in (1, 2, 3)]
assert all(len(a) == 1080 for a in coef), [len(a) for a in coef]
assert all(len(a) == 120 for a in rad), [len(a) for a in rad]

def fmt(values):
    lines, row = [], []
    for v in values:
        row.append(repr(v))
        if len(row) == 6:
            lines.append("        " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("        " + ", ".join(row) + ",")
    return "\n".join(lines)

out = ["// <auto-generated> validation/gen_hosek_wilkie_data.py: do not edit by hand. </auto-generated>",
       "//",
       "// Hosek-Wilkie sky model, RGB data (reference implementation 1.4a).",
       "// Original copyright and license, which this file must carry:",
       "//"]
out += ["// " + line if line.strip() else "//" for line in license_block.splitlines()]
out += ["",
        "namespace RayTracer.Rendering.Sky;",
        "",
        "internal static class HosekWilkieData",
        "{"]
for c, ch in enumerate("RGB"):
    out += [f"    /// <summary>Distribution coefficients, channel {ch}: [albedo][turbidity][control point][9].</summary>",
            f"    public static readonly double[] Coefficients{ch} =", "    {", fmt(coef[c]), "    };", ""]
    out += [f"    /// <summary>Radiance scale, channel {ch}: [albedo][turbidity][control point].</summary>",
            f"    public static readonly double[] Radiance{ch} =", "    {", fmt(rad[c]), "    };", ""]
out[-1:] = ["}"]
dest = pathlib.Path(__file__).resolve().parent.parent / "src/RayTracer/Rendering/Sky/HosekWilkieData.cs"
dest.write_text("\n".join(out) + "\n")
print(f"wrote {dest} ({sum(len(a) for a in coef + rad)} values)")
