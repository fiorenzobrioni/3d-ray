"""Generates Materials/DielectricAlbedo.Data.cs: the directional albedo of the
reflection lobe of a rough dielectric seen from the outside (eta >= 1), with
GGX, height-correlated Smith G2 and the exact unpolarised Fresnel factor,

    E_R(mu, alpha, eta) = integral of F(v.h, eta) D(h) G2(v, l) / (4 mu) over the upper hemisphere,

and the hemispherical average of the Fresnel factor itself,
E_F(eta) = 2 integral F(mu, eta) mu dmu. The OpenPBR layering (PIANO-REVIEW.md,
Phase 5) scales what lies under a specular interface by 1 - E_R, and the coat
darkening uses E_F.

eta is indexed by s = sqrt(F0) = (eta - 1) / (eta + 1) in [0, 1]: s = 0 is an
invisible interface (E_R = 0), s = 1 a perfect reflector (E_R = the white
table of gen_microfacet_albedo.py). E_R is close to quadratic in s, so linear
interpolation on 17 nodes stays within 1e-3.

Same deterministic visible-normal quadrature as gen_microfacet_albedo.py: the
integrand is F G2 / G1(v) on an N x N midpoint grid, no Monte Carlo noise.

    python3 validation/gen_dielectric_albedo.py   (numpy only, a few minutes)
"""
import numpy as np, pathlib

N = 512                 # quadrature points per axis of the VNDF square
MU, RO, ET = 33, 32, 17  # mu = i / 32, roughness = j / 31 (alpha = roughness^2), s = k / 16
FAVG = 65               # E_F nodes, s = k / 64

u = (np.arange(N) + 0.5) / N
U1, U2 = np.meshgrid(u, u, indexing="ij")
U1, U2 = U1.ravel(), U2.ravel()


def fresnel(c, eta):
    """Exact unpolarised reflectance from the outside, relative IOR eta >= 1."""
    if eta == np.inf:
        return np.ones_like(c)
    if eta == 1.0:
        return np.zeros_like(c)
    g = np.sqrt(eta * eta - 1.0 + c * c)
    a = (g - c) / (g + c)
    b = (c * (g + c) - 1.0) / (c * (g - c) + 1.0)
    return 0.5 * a * a * (1.0 + b * b)


def eta_of(s):
    return np.inf if s >= 1.0 else (1.0 + s) / (1.0 - s)


def lam(wx, wy, wz, a):
    return 0.5 * (-1.0 + np.sqrt(1.0 + a * a * (wx * wx + wy * wy) / (wz * wz)))


def weights(mu, a):
    """Visible-normal samples for view cosine mu: the G2/G1 weight of every
    sample that reflects above the horizon, and its v.h."""
    mu = max(mu, 1e-4)
    vx, vy, vz = np.sqrt(1.0 - mu * mu), 0.0, mu
    hx, hy, hz = a * vx, a * vy, vz
    n = np.sqrt(hx * hx + hy * hy + hz * hz); hx, hy, hz = hx / n, hy / n, hz / n
    l2 = hx * hx + hy * hy
    t1x, t1y = (-hy / np.sqrt(l2), hx / np.sqrt(l2)) if l2 > 0 else (1.0, 0.0)
    t2x, t2y, t2z = hy * 0 - hz * t1y, hz * t1x - hx * 0, hx * t1y - hy * t1x
    r = np.sqrt(U1); phi = 2 * np.pi * U2
    p1 = r * np.cos(phi); p2 = r * np.sin(phi)
    s = 0.5 * (1.0 + hz)
    p2 = (1 - s) * np.sqrt(np.maximum(0, 1 - p1 * p1)) + s * p2
    p3 = np.sqrt(np.maximum(0, 1 - p1 * p1 - p2 * p2))
    nx = p1 * t1x + p2 * t2x + p3 * hx
    ny = p1 * t1y + p2 * t2y + p3 * hy
    nz = p2 * t2z + p3 * hz
    mx, my, mz = a * nx, a * ny, np.maximum(0, nz)
    m = np.sqrt(mx * mx + my * my + mz * mz); mx, my, mz = mx / m, my / m, mz / m
    vdh = vx * mx + vy * my + vz * mz
    lx, ly, lz = 2 * vdh * mx - vx, 2 * vdh * my - vy, 2 * vdh * mz - vz
    up = lz > 1e-12
    lv = lam(vx, vy, vz, a)
    ll = lam(lx[up], ly[up], lz[up], a)
    return (1 + lv) / (1 + lv + ll), np.clip(vdh[up], 0.0, 1.0)


E = np.zeros((MU, RO, ET))
for j in range(RO):
    a = max((j / (RO - 1)) ** 2, 1e-4)
    for i in range(MU):
        w, c = weights(i / (MU - 1), a)
        for k in range(ET):
            E[i, j, k] = float(np.sum(w * fresnel(c, eta_of(k / (ET - 1)))) / U1.size)
    print(f"roughness {np.sqrt(a):.3f}: E_R(mu=1, eta=1.5) ~ {E[-1, j, 3]:.5f}", flush=True)

# E_F(eta): Simpson on 4097 nodes of mu (F is smooth for eta >= 1).
mus = np.linspace(0.0, 1.0, 4097)
wS = np.ones_like(mus); wS[1:-1:2] = 4; wS[2:-1:2] = 2
Favg = np.array([2 * np.sum(wS * fresnel(mus, eta_of(k / (FAVG - 1))) * mus) / (3 * (mus.size - 1))
                 for k in range(FAVG)])


def rows(arr):
    return ",\n".join("        " + ", ".join(f"{v:.6f}f" for v in row) for row in arr)


out = f"""// <auto-generated>
// Generated by validation/gen_dielectric_albedo.py: do not edit by hand.
// </auto-generated>
namespace RayTracer.Materials;

internal static partial class DielectricAlbedo
{{
    private const int MuRes = {MU}, RoughRes = {RO}, SRes = {ET}, FavgRes = {FAVG};

    // E_R[mu, roughness, s]: mu = i / {MU - 1}, roughness = j / {RO - 1} (alpha = roughness^2),
    // s = k / {ET - 1} = (eta - 1) / (eta + 1).
    private static readonly float[] Table =
    {{
{rows(E.reshape(MU * RO, ET))}
    }};

    // E_F[s], s = k / {FAVG - 1}.
    private static readonly float[] FresnelAverage =
    {{
{rows(Favg.reshape(-1, 13))}
    }};
}}
"""
pathlib.Path("src/RayTracer/Materials/DielectricAlbedo.Data.cs").write_text(out)
print("written")
