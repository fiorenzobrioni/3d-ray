"""Generates Materials/MicrofacetAlbedo.Data.cs: the directional albedo of a
white single-scattering GGX reflector with height-correlated Smith G2,

    E(mu, alpha) = integral of D(h) G2(v, l) / (4 mu) over the upper hemisphere,

and its cosine-weighted average E_avg(alpha) = 2 integral E(mu) mu dmu, used by
the Kulla-Conty multiple-scattering lobe (PIANO-REVIEW.md, Phase 5).

E is integrated over the visible-normal (VNDF, Heitz 2018) parametrisation,
where the integrand is G2 / G1(v): a deterministic midpoint rule on an
N x N grid of the two uniforms, no Monte Carlo noise.

    python3 validation/gen_microfacet_albedo.py   (numpy only, a few minutes)
"""
import numpy as np, pathlib

N = 768           # quadrature points per axis of the VNDF square
MU, RO = 33, 32   # table resolution: mu = i / 32 = cos(theta_v), roughness = sqrt(alpha)
FINE = 64         # E is computed at mu = k / 64; the table keeps the even nodes and
                  # E_avg integrates all of them with Simpson's rule (E is smooth)

u = (np.arange(N) + 0.5) / N
U1, U2 = np.meshgrid(u, u, indexing="ij")
U1, U2 = U1.ravel(), U2.ravel()


def lam(wx, wy, wz, a):
    return 0.5 * (-1.0 + np.sqrt(1.0 + a * a * (wx * wx + wy * wy) / (wz * wz)))


def albedo(mu, a):
    mu = max(mu, 1e-4)
    vx, vy, vz = np.sqrt(1.0 - mu * mu), 0.0, mu
    hx, hy, hz = a * vx, a * vy, vz
    n = np.sqrt(hx * hx + hy * hy + hz * hz); hx, hy, hz = hx / n, hy / n, hz / n
    l2 = hx * hx + hy * hy
    t1x, t1y = (-hy / np.sqrt(l2), hx / np.sqrt(l2)) if l2 > 0 else (1.0, 0.0)
    t2x, t2y, t2z = hy * 0 - hz * t1y, hz * t1x - hx * 0, hx * t1y - hy * t1x
    r = np.sqrt(U1); phi = 2 * np.pi * U2
    p1 = r * np.cos(phi); p2 = r * np.sin(phi)
    s = 0.5 * (1.0 + hz)
    p2 = (1 - s) * np.sqrt(np.maximum(0, 1 - p1 * p1)) + s * p2
    p3 = np.sqrt(np.maximum(0, 1 - p1 * p1 - p2 * p2))
    nx = p1 * t1x + p2 * t2x + p3 * hx
    ny = p1 * t1y + p2 * t2y + p3 * hy
    nz = p2 * t2z + p3 * hz
    mx, my, mz = a * nx, a * ny, np.maximum(0, nz)
    m = np.sqrt(mx * mx + my * my + mz * mz); mx, my, mz = mx / m, my / m, mz / m
    vdh = vx * mx + vy * my + vz * mz
    lx, ly, lz = 2 * vdh * mx - vx, 2 * vdh * my - vy, 2 * vdh * mz - vz
    up = lz > 1e-12
    lv = lam(vx, vy, vz, a)
    ll = lam(lx[up], ly[up], lz[up], a)
    return float(np.sum((1 + lv) / (1 + lv + ll)) / U1.size)


def alpha_of(j):
    return max((j / (RO - 1)) ** 2, 1e-4)


E = np.zeros((MU, RO))
Eavg = np.zeros(RO)
for j in range(RO):
    a = alpha_of(j)
    fine = np.array([albedo(k / FINE, a) for k in range(FINE + 1)])
    E[:, j] = fine[::2]
    mu = np.arange(FINE + 1) / FINE
    w = np.ones(FINE + 1); w[1:-1:2] = 4; w[2:-1:2] = 2
    Eavg[j] = 2 * np.sum(w * fine * mu) / (3 * FINE)
    print(f"roughness {np.sqrt(a):.3f}: E(mu=1) {E[-1, j]:.5f}  E_avg {Eavg[j]:.5f}", flush=True)


def rows(arr):
    return ",\n".join("        " + ", ".join(f"{v:.6f}f" for v in row) for row in arr)


out = f"""// <auto-generated>
// Generated by validation/gen_microfacet_albedo.py: do not edit by hand.
// </auto-generated>
namespace RayTracer.Materials;

internal static partial class MicrofacetAlbedo
{{
    private const int MuRes = {MU}, RoughRes = {RO};

    // E[mu, roughness]: mu = i / {MU - 1}, roughness = j / {RO - 1} (alpha = roughness^2).
    private static readonly float[] Table =
    {{
{rows(E)}
    }};

    // E_avg[roughness].
    private static readonly float[] Average =
    {{
{rows(Eavg.reshape(1, -1))}
    }};
}}
"""
pathlib.Path("src/RayTracer/Materials/MicrofacetAlbedo.Data.cs").write_text(out)
print("written")
