"""Generates Materials/AnisotropicAlbedo.Data.cs: the directional albedo of a
white single-scattering anisotropic GGX reflector with height-correlated Smith
G2, as a function of the view direction (cosine mu and azimuth phi from the
tangent) and of the OpenPBR roughness r and anisotropy a,

    alpha_t = r^2 sqrt(2 / (1 + (1 - a)^2)),  alpha_b = (1 - a) alpha_t.

The isotropic table read at the roughness projected on the view azimuth is
close but not exact for a strongly anisotropic lobe (+6.6% of energy at
a = 0.72, r = 0.5); this table is (PIANO-REVIEW.md, Phase 5). E is symmetric in
phi about both axes, so phi spans [0, pi/2].

Same deterministic visible-normal quadrature as gen_microfacet_albedo.py.

    python3 validation/gen_aniso_albedo.py   (numpy only, ~15 minutes)
"""
import numpy as np, pathlib

N = 192                          # quadrature points per axis of the VNDF square
MU, PHI, RO, AN = 17, 9, 16, 9   # mu = i/16, phi = k/8 * pi/2, r = j/15, a = l/8

u = (np.arange(N) + 0.5) / N
U1, U2 = np.meshgrid(u, u, indexing="ij")
U1, U2 = U1.ravel(), U2.ravel()


def alphas(r, a):
    at = r * r * np.sqrt(2.0 / (1.0 + (1.0 - a) ** 2))
    return max(at, 1e-4), max((1.0 - a) * at, 1e-4)


def lam(wx, wy, wz, ax, ay):
    return 0.5 * (-1.0 + np.sqrt(1.0 + (ax * ax * wx * wx + ay * ay * wy * wy) / (wz * wz)))


def albedo(mu, phi, ax, ay):
    mu = max(mu, 1e-4)
    s = np.sqrt(1.0 - mu * mu)
    vx, vy, vz = s * np.cos(phi), s * np.sin(phi), mu
    hx, hy, hz = ax * vx, ay * vy, vz
    n = np.sqrt(hx * hx + hy * hy + hz * hz); hx, hy, hz = hx / n, hy / n, hz / n
    l2 = hx * hx + hy * hy
    t1x, t1y = (-hy / np.sqrt(l2), hx / np.sqrt(l2)) if l2 > 0 else (1.0, 0.0)
    t2x, t2y, t2z = -hz * t1y, hz * t1x, hx * t1y - hy * t1x
    r = np.sqrt(U1); ph = 2 * np.pi * U2
    p1 = r * np.cos(ph); p2 = r * np.sin(ph)
    sh = 0.5 * (1.0 + hz)
    p2 = (1 - sh) * np.sqrt(np.maximum(0, 1 - p1 * p1)) + sh * p2
    p3 = np.sqrt(np.maximum(0, 1 - p1 * p1 - p2 * p2))
    nx = p1 * t1x + p2 * t2x + p3 * hx
    ny = p1 * t1y + p2 * t2y + p3 * hy
    nz = p2 * t2z + p3 * hz
    mx, my, mz = ax * nx, ay * ny, np.maximum(0, nz)
    m = np.sqrt(mx * mx + my * my + mz * mz); mx, my, mz = mx / m, my / m, mz / m
    vdh = vx * mx + vy * my + vz * mz
    lx, ly, lz = 2 * vdh * mx - vx, 2 * vdh * my - vy, 2 * vdh * mz - vz
    up = lz > 1e-12
    lv = lam(vx, vy, vz, ax, ay)
    ll = lam(lx[up], ly[up], lz[up], ax, ay)
    return float(np.sum((1 + lv) / (1 + lv + ll)) / U1.size)


E = np.zeros((RO, AN, MU, PHI))
for j in range(RO):
    for l in range(AN):
        ax, ay = alphas(j / (RO - 1), l / (AN - 1))
        for i in range(MU):
            for k in range(PHI):
                E[j, l, i, k] = albedo(i / (MU - 1), k / (PHI - 1) * np.pi / 2, ax, ay)
    print(f"roughness {j / (RO - 1):.3f}: E(mu=1) {E[j, 0, -1, 0]:.5f}", flush=True)


def rows(arr):
    return ",\n".join("        " + ", ".join(f"{v:.6f}f" for v in row) for row in arr)


out = f"""// <auto-generated>
// Generated by validation/gen_aniso_albedo.py: do not edit by hand.
// </auto-generated>
namespace RayTracer.Materials;

internal static partial class AnisotropicAlbedo
{{
    private const int RoughRes = {RO}, AnisoRes = {AN}, MuRes = {MU}, PhiRes = {PHI};

    // E[roughness, anisotropy, mu, phi]: roughness = j / {RO - 1}, anisotropy = l / {AN - 1},
    // mu = i / {MU - 1}, phi = k / {PHI - 1} * pi / 2 (azimuth from the tangent).
    private static readonly float[] Table =
    {{
{rows(E.reshape(RO * AN * MU, PHI))}
    }};
}}
"""
pathlib.Path("src/RayTracer/Materials/AnisotropicAlbedo.Data.cs").write_text(out)
print("written")
